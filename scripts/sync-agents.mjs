// Mirrors the canonical agent config (AGENTS.md + .claude/) into Antigravity's .agent/ folder.
// Run after editing AGENTS.md or anything in .claude/: node scripts/sync-agents.mjs
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, '.claude');
const out = join(root, '.agent');
const GENERATED = '<!-- Generated by scripts/sync-agents.mjs — edit the source in .claude/ or AGENTS.md -->\n';

const read = (p) => readFileSync(p, 'utf8');
const listMd = (dir) => (existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.md')) : []);

function splitFrontmatter(text) {
  const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!match) return { meta: {}, body: text };
  const meta = Object.fromEntries(
    match[1]
      .split(/\r?\n/)
      .map((line) => line.match(/^(\w[\w-]*):\s*(.*)$/))
      .filter(Boolean)
      .map(([, k, v]) => [k, v]),
  );
  return { meta, body: text.slice(match[0].length) };
}

function writeWorkflow(name, description, body) {
  const text = body.replaceAll('$ARGUMENTS', 'the task the user described');
  writeFileSync(join(out, 'workflows', `${name}.md`), `---\ndescription: ${description}\n---\n${GENERATED}\n${text}`);
}

rmSync(out, { recursive: true, force: true });
for (const dir of ['rules', 'workflows', 'skills']) mkdirSync(join(out, dir), { recursive: true });

// Always-on rule from AGENTS.md
writeFileSync(join(out, 'rules', 'redrelay.md'), `---\ntrigger: always_on\n---\n${GENERATED}\n${read(join(root, 'AGENTS.md'))}`);

// Skills: same SKILL.md format, copied as-is
const skillsDir = join(src, 'skills');
if (existsSync(skillsDir)) cpSync(skillsDir, join(out, 'skills'), { recursive: true });

// Slash commands → workflows
for (const file of listMd(join(src, 'commands'))) {
  const { meta, body } = splitFrontmatter(read(join(src, 'commands', file)));
  writeWorkflow(file.replace(/\.md$/, ''), meta.description ?? '', body);
}

// Subagents → review workflows (Antigravity has no subagents)
for (const file of listMd(join(src, 'agents'))) {
  const { meta, body } = splitFrontmatter(read(join(src, 'agents', file)));
  writeWorkflow(`agent-${meta.name ?? file.replace(/\.md$/, '')}`, meta.description ?? '', body);
}

console.log('Synced .claude/ + AGENTS.md → .agent/');
